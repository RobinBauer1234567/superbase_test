CREATE OR REPLACE FUNCTION public.catch_up_matchdays_for_new_user(p_league_id bigint, p_user_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_season_id bigint;
    v_round_rec RECORD;
BEGIN
    -- 1. Saison der Liga herausfinden
    SELECT season_id INTO v_season_id FROM public.leagues WHERE id = p_league_id;

    -- 2. Finde alle Spieltage, die bereits laufen oder schon vorbei sind
    FOR v_round_rec IN 
        SELECT round, status 
        FROM public.spieltag 
        WHERE season_id = v_season_id 
          AND status IN ('läuft', 'beendet', 'final')
        ORDER BY round ASC
    LOOP
        -- a) Snapshot erstellen: Kopiert das frisch zugeloste Team auf die Bank (Index 99)
        -- und sperrt direkt die Spieler, deren Spiele schon laufen/beendet sind.
        PERFORM public.initialize_matchday_snapshot(p_league_id, p_user_id, v_season_id, v_round_rec.round);

        -- b) Den gesamten Spieltag (Header) für Formationsänderungen sperren
        -- Da der Spieltag mindestens 'läuft', ist der Anpfiff des ersten Spiels bereits durch.
        UPDATE public.user_matchday_points
        SET is_locked = true
        WHERE user_id = p_user_id 
          AND league_id = p_league_id 
          AND season_id = v_season_id 
          AND round = v_round_rec.round;
          
    END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.check_and_unlock_dependencies()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_team RECORD;
    v_open_squads INT;
BEGIN
    IF NEW.status = 'COMPLETED' AND OLD.status IS DISTINCT FROM 'COMPLETED' THEN
        
        -- A) Normale, lineare Abhängigkeiten auflösen
        UPDATE public.sync_tasks
        SET status = 'PENDING'
        WHERE depends_on_task_id = NEW.id AND status = 'WAITING';
          
        -- B) FAN-OUT: Wenn die Teams fertig geladen sind...
        IF NEW.task_type = 'FETCH_TEAMS' THEN
            INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, priority, status)
            VALUES ('FETCH_ROUNDS', NEW.tournament_id, NEW.season_id, 10, 'WAITING_FOR_SQUADS');

            FOR v_team IN SELECT team_id FROM public.season_teams WHERE season_id = NEW.season_id LOOP
                INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, team_id, priority, status)
                VALUES ('FETCH_TEAM_SQUAD', NEW.tournament_id, NEW.season_id, v_team.team_id, 10, 'PENDING');
            END LOOP;
        END IF;

        -- C) FAN-IN: Wenn ein einzelner Kader-Task fertig ist...
        IF NEW.task_type = 'FETCH_TEAM_SQUAD' THEN
            
            -- FIX: Wir suchen nach JEDEM Task, der noch nicht erfolgreich war (also auch FAILED)
            SELECT count(*) INTO v_open_squads FROM public.sync_tasks
            WHERE season_id = NEW.season_id 
              AND task_type = 'FETCH_TEAM_SQUAD' 
              AND status != 'COMPLETED';

            -- Nur wenn wirklich ALLE Kader auf COMPLETED stehen, geht es weiter!
            IF v_open_squads = 0 THEN
                UPDATE public.sync_tasks 
                SET status = 'PENDING'
                WHERE season_id = NEW.season_id 
                  AND task_type = 'FETCH_ROUNDS' 
                  AND status = 'WAITING_FOR_SQUADS';
            END IF;
        END IF;

        -- D) Wenn die Runden fertig sind, schalten wir die Spiele frei
        IF NEW.task_type = 'FETCH_ROUNDS' THEN
            INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, priority, status)
            VALUES ('FETCH_MATCHES', NEW.tournament_id, NEW.season_id, 10, 'PENDING');
        END IF;

        -- E) Wenn die Spiele fertig geladen wurden, ist die Initialisierung abgeschlossen!
        IF NEW.task_type = 'FETCH_MATCHES' THEN
            UPDATE public.season 
            SET is_initialized = true 
            WHERE id = NEW.season_id;
        END IF;

    -- Das hier lassen wir zur Sicherheit drin, greift bei linearen Tasks:
    ELSIF NEW.status = 'FAILED' AND OLD.status IS DISTINCT FROM 'FAILED' THEN
        UPDATE public.sync_tasks
        SET status = 'FAILED', error_message = 'Vorgänger-Task fehlgeschlagen.'
        WHERE depends_on_task_id = NEW.id AND status = 'WAITING';
    END IF;
    
    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.check_schedule_update_needed(p_season_id bigint)
 RETURNS boolean
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_last timestamp with time zone;
BEGIN
    SELECT last_schedule_update INTO v_last FROM public.season WHERE id = p_season_id;
    -- Wenn das Datum null ist oder älter als 2 Tage
    IF v_last IS NULL OR v_last < (now() - interval '2 days') THEN
        RETURN true;
    END IF;
    RETURN false;
END;
