CREATE OR REPLACE FUNCTION public.jsonb_add(a jsonb, b jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
  rec RECORD;
  result JSONB := '{}'::JSONB;
BEGIN
  -- Iteriere über alle Key/Value-Paare in a, aber nur wenn der Wert vom Typ 'number' ist.
  FOR rec IN
    SELECT key, (value::text)::NUMERIC AS num
    FROM jsonb_each(a)
    WHERE jsonb_typeof(value) = 'number'
  LOOP
    result := result || jsonb_build_object(
      rec.key, 
      rec.num + COALESCE(
        CASE 
          WHEN jsonb_typeof(b->rec.key) = 'number' 
          THEN (b->>rec.key)::NUMERIC 
          ELSE 0 
        END, 
      0)
    );
  END LOOP;

  -- Füge Keys aus b hinzu, die noch nicht in a vorkamen und deren Wert eine Zahl ist.
  FOR rec IN
    SELECT key, (value::text)::NUMERIC AS num
    FROM jsonb_each(b)
    WHERE jsonb_typeof(value) = 'number'
  LOOP
    IF NOT (result ? rec.key) THEN
      result := result || jsonb_build_object(rec.key, rec.num);
    END IF;
  END LOOP;

  RETURN result;
END;
$function$;

