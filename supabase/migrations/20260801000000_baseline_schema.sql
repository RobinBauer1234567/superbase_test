    -- Name UND Profilbild holen
    SELECT username, avatar_url INTO v_user_name, v_avatar_url 
    FROM profiles 
    WHERE user_id = v_target_user_id;
    
    IF (TG_OP = 'INSERT') THEN
        INSERT INTO league_activities (league_id, type, content)
        VALUES (NEW.league_id, 'JOIN', jsonb_build_object(
            'user_id', v_target_user_id,
            'user_name', v_user_name,
            'avatar_url', v_avatar_url
        ));
        RETURN NEW;
    ELSIF (TG_OP = 'DELETE') THEN
        INSERT INTO league_activities (league_id, type, content)
        VALUES (OLD.league_id, 'LEAVE', jsonb_build_object(
            'user_id', v_target_user_id,
            'user_name', v_user_name,
            'avatar_url', v_avatar_url
        ));
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$function$;

