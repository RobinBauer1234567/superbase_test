CREATE OR REPLACE FUNCTION public.assign_random_team(p_league_id bigint, p_user_id uuid)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_num_players int;
    v_target_val numeric;
    v_min_val numeric;
    v_max_val numeric;
    v_player_ids bigint[];
    v_total_val numeric;
    v_season_id int;
    v_retry int := 0;
BEGIN
    SELECT num_starting_players, starting_team_value, season_id
    INTO v_num_players, v_target_val, v_season_id
    FROM leagues WHERE id = p_league_id;

    IF v_num_players <= 0 THEN RETURN; END IF;

    v_min_val := GREATEST(0, v_target_val - 1000000);
    v_max_val := v_target_val + 1000000;

    LOOP
        EXIT WHEN v_retry >= 50;
        v_retry := v_retry + 1;

        SELECT ARRAY_agg(pid), SUM(mkw)
        INTO v_player_ids, v_total_val
        FROM (
            SELECT s.id as pid, COALESCE(sa.marktwert, 0) as mkw
            FROM public.spieler s
            -- NEU: Saison-Filter im JOIN
            JOIN public.spieler_analytics sa ON sa.spieler_id = s.id AND sa.season_id = v_season_id
            JOIN public.season_players sp ON sp.player_id = s.id
            WHERE sp.season_id = v_season_id
            AND sa.marktwert > 0
            AND s.id NOT IN (
                SELECT player_id FROM public.league_players WHERE league_id = p_league_id
            )
            ORDER BY random()
            LIMIT v_num_players
        ) sub;

        IF array_length(v_player_ids, 1) = v_num_players 
           AND v_total_val >= v_min_val 
           AND v_total_val <= v_max_val THEN
            EXIT;
        END IF;
    END LOOP;

    IF v_player_ids IS NOT NULL THEN
        INSERT INTO public.league_players (league_id, user_id, player_id, purchase_price)
        SELECT p_league_id, p_user_id, unnest(v_player_ids), 0
        ON CONFLICT (league_id, player_id) DO NOTHING;
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.buy_player_now(p_transfer_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  t_row RECORD; buyer_budget BIGINT; current_user_id UUID := auth.uid(); v_player RECORD; v_season_id bigint;
  v_seller_name text := 'System'; v_seller_avatar text := NULL; v_buyer_name text; v_buyer_avatar text;
BEGIN
  SELECT * INTO t_row FROM transfer_market WHERE id = p_transfer_id AND is_active = true FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Transfer nicht gefunden.'; END IF;

  SELECT budget INTO buyer_budget FROM league_members WHERE user_id = current_user_id AND league_id = t_row.league_id FOR UPDATE;
  IF buyer_budget < t_row.buy_now_price THEN RAISE EXCEPTION 'Nicht genug Budget.'; END IF;

  UPDATE league_members SET budget = budget - t_row.buy_now_price WHERE user_id = current_user_id AND league_id = t_row.league_id;
  IF t_row.seller_id IS NOT NULL THEN
    UPDATE league_members SET budget = budget + t_row.buy_now_price WHERE user_id = t_row.seller_id AND league_id = t_row.league_id;
    SELECT username, avatar_url INTO v_seller_name, v_seller_avatar FROM profiles WHERE user_id = t_row.seller_id;
  END IF;

  SELECT username, avatar_url INTO v_buyer_name, v_buyer_avatar FROM profiles WHERE user_id = current_user_id;
  SELECT season_id INTO v_season_id FROM leagues WHERE id = t_row.league_id;
  
  -- JOIN über season_players statt spieler.team_id
  SELECT s.name, s.position, s.profilbild_url, t.image_url AS team_image_url, sa.marktwert, sa.punkteschnitt 
  INTO v_player FROM spieler s 
  LEFT JOIN season_players sp ON sp.player_id = s.id AND sp.season_id = v_season_id AND sp.is_active = true
  LEFT JOIN team t ON sp.team_id = t.id 
  LEFT JOIN spieler_analytics sa ON sa.spieler_id = s.id AND sa.season_id = v_season_id 
  WHERE s.id = t_row.player_id;

  PERFORM set_config('my.skip_trigger', 'true', true);
  INSERT INTO league_players (league_id, user_id, player_id, purchase_price) VALUES (t_row.league_id, current_user_id, t_row.player_id, t_row.buy_now_price);

  INSERT INTO league_activities (league_id, type, content) VALUES (t_row.league_id, 'TRANSFER', jsonb_build_object(
      'transfer_type', 'SOFORTKAUF', 'transfer_id', t_row.id, 'player_id', t_row.player_id, 'position', v_player.position, 'player_name', v_player.name,
      'profilbild_url', v_player.profilbild_url, 'team_image_url', v_player.team_image_url, 'marktwert', v_player.marktwert, 'score', ROUND(COALESCE(v_player.punkteschnitt, 0)),
      'buyer_name', v_buyer_name, 'buyer_avatar_url', v_buyer_avatar, 'seller_name', v_seller_name, 'seller_avatar_url', v_seller_avatar, 'price', t_row.buy_now_price, 'is_system_buy', (t_row.seller_id IS NULL)
  ));
  UPDATE transfer_market SET is_active = false WHERE id = t_row.id;
