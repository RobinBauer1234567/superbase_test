        RAISE EXCEPTION 'Fehler: game_settings (id=1) wurde nicht gefunden. Update abgebrochen!';
    END IF;

    SELECT id INTO v_current_season 
    FROM public.season 
    ORDER BY id DESC 
    LIMIT 1;
    
    IF v_current_season IS NULL THEN
        RAISE NOTICE 'Keine aktive Saison gefunden. Abbruch.';
        RETURN;
    END IF;

    PERFORM public.update_all_matchup_faktors(v_current_season);
    PERFORM public.update_all_spieler_analytics(v_current_season);

    -- GEFIXT: Update nur für die aktuelle Saison ausführen
    UPDATE public.spieler_analytics
    SET 
        calculated_marktwert = ROUND(v_settings.mw_multiplier * power(COALESCE(expected_points, 0), v_settings.mw_exponent) + v_settings.mw_base_value),
        marktwert = ROUND(
            marktwert + (
                (v_settings.mw_multiplier * power(COALESCE(expected_points, 0), v_settings.mw_exponent) + v_settings.mw_base_value) - marktwert
            ) * v_settings.mw_daily_adjustment
        ),
        last_updated_at = now()
    WHERE season_id = v_current_season;

    RAISE NOTICE 'Tägliches Marktwert-Update mit dynamischen Settings erfolgreich abgeschlossen!';
END;
$function$;

