CREATE OR REPLACE FUNCTION public.transform_statistics(input jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
  mp NUMERIC;
  rec RECORD;
  result JSONB := '{}'::JSONB;
BEGIN
  -- Versuche, den Wert für minutesPlayed auszulesen
  mp := (input->>'minutesPlayed')::NUMERIC;
  
  FOR rec IN SELECT key, value FROM jsonb_each(input)
  LOOP
    IF rec.key IN ('rating', 'minutesPlayed') THEN
      -- Diese Keys werden unverändert übernommen
      result := result || jsonb_build_object(rec.key, rec.value);
    ELSIF jsonb_typeof(rec.value) = 'number' THEN
      IF mp IS NOT NULL AND mp >= 1 THEN
        -- Transformation: (Wert / minutesPlayed) * 90
        result := result || jsonb_build_object(rec.key, ((rec.value::text)::NUMERIC / mp) * 90);
      ELSE
        result := result || jsonb_build_object(rec.key, rec.value);
      END IF;
    ELSE
      -- Falls der Wert kein reiner numerischer Wert ist (z.B. ein verschachteltes Objekt),
      -- wird er unverändert übernommen.
      result := result || jsonb_build_object(rec.key, rec.value);
    END IF;
  END LOOP;
  RETURN result;
END;
$function$;

