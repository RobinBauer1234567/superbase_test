CREATE OR REPLACE FUNCTION public.initialize_matchday_snapshot(p_league_id bigint, p_user_id uuid, p_season_id bigint, p_round integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_prev_matchday_point_id bigint;
    v_prev_formation text;
    v_new_matchday_point_id bigint;
BEGIN
    -- 1. Schutz: Prüfen, ob Snapshot bereits existiert
    IF EXISTS (
        SELECT 1 FROM public.user_matchday_points 
        WHERE user_id = p_user_id 
          AND league_id = p_league_id 
          AND round = p_round
    ) THEN
        RETURN;
    END IF;

    -- 2. Vorherigen Spieltag suchen (nächstkleinere Runde)
    SELECT id, formation
    INTO v_prev_matchday_point_id, v_prev_formation
    FROM public.user_matchday_points
    WHERE user_id = p_user_id 
      AND league_id = p_league_id 
      AND round < p_round
    ORDER BY round DESC
    LIMIT 1;

    -- Fallback: Strikt 4-4-2
    IF v_prev_formation IS NULL THEN
        v_prev_formation := '4-4-2';
    END IF;

    -- 3. Neue Zeile in user_matchday_points anlegen
    INSERT INTO public.user_matchday_points (
        user_id, 
        league_id, 
        season_id, 
        round, 
        formation, 
        total_points, 
        is_locked
    ) VALUES (
        p_user_id, 
        p_league_id, 
        p_season_id, 
        p_round, 
        v_prev_formation, 
        0, 
        false 
    ) RETURNING id INTO v_new_matchday_point_id;

    -- 4. Spieler kopieren, Indizes übernehmen, Spielstatus prüfen 
    INSERT INTO public.user_matchday_players (
        matchday_point_id, 
        player_id, 
        formation_index, 
        is_locked,
        spiel_id,
        matchrating_id,
        points
    )
    SELECT 
        v_new_matchday_point_id,
        lp.player_id,
        COALESCE(prev_ump.formation_index, 99),
        CASE 
            WHEN s.status IS NOT NULL AND s.status != 'nicht gestartet' THEN true
            ELSE false
        END AS is_locked,
        s.id AS spiel_id,
        mr.id AS matchrating_id,
        COALESCE(mr.punkte, 0) AS points
    FROM public.league_players lp
    LEFT JOIN public.user_matchday_players prev_ump 
        ON prev_ump.player_id = lp.player_id 
       AND prev_ump.matchday_point_id = v_prev_matchday_point_id
    LEFT JOIN public.season_players sp 
        -- FIX: sp.is_active = true hinzugefügt
        ON sp.player_id = lp.player_id 
       AND sp.season_id = p_season_id
       AND sp.is_active = true
    LEFT JOIN public.spiel s 
        ON s.season_id = p_season_id 
       AND s.round = p_round 
       AND (s.heimteam_id = sp.team_id OR s.auswärtsteam_id = sp.team_id)
    LEFT JOIN public.matchrating mr 
        ON mr.spiel_id = s.id 
       AND mr.spieler_id = lp.player_id
    WHERE lp.user_id = p_user_id 
      AND lp.league_id = p_league_id;

    -- 5. Gesamtpunkte direkt einmal kalkulieren!
    UPDATE public.user_matchday_points
    SET total_points = (
        SELECT COALESCE(SUM(points), 0)
        FROM public.user_matchday_players
        WHERE matchday_point_id = v_new_matchday_point_id
          AND formation_index <= 10
    )
    WHERE id = v_new_matchday_point_id;
      
END;
$function$;

