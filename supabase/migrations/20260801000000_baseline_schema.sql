CREATE OR REPLACE FUNCTION public.sync_matchday_points()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    r RECORD;
BEGIN
    -- 1. Zuerst das Update auf die Live-Punkte ausführen
    UPDATE public.user_matchday_players
    SET points = NEW.punkte,
        matchrating_id = NEW.id
    WHERE player_id = NEW.spieler_id 
      AND spiel_id = NEW.spiel_id;

    -- 2. Wenn mindestens eine Zeile geupdatet wurde, berechnen wir die Gesamtpunkte neu
    IF FOUND THEN
        FOR r IN (
            -- Wir holen uns die betroffenen Snapshot-IDs
            SELECT matchday_point_id 
            FROM public.user_matchday_players
            WHERE player_id = NEW.spieler_id 
              AND spiel_id = NEW.spiel_id
        )
        LOOP
            -- Wir summieren die Punkte der Startelf (Index 0-10) für diesen Eintrag auf
            UPDATE public.user_matchday_points
            SET total_points = (
                SELECT COALESCE(SUM(points), 0)
                FROM public.user_matchday_players
                WHERE matchday_point_id = r.matchday_point_id
                  AND formation_index <= 10
            )
            WHERE id = r.matchday_point_id;
        END LOOP;
    END IF;

    RETURN NEW;
END;
