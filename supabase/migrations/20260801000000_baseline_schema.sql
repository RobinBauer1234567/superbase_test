CREATE OR REPLACE FUNCTION public.init_player_from_sofascore(p_player_id bigint, p_formation text, p_lineup_index integer, p_api_position text, p_ratings numeric[])
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_final_position text;
    v_avg_points numeric := 0;
    v_calc_mw bigint;
    v_rating numeric;
    v_points_sum numeric := 0;
    v_points_count int := 0;
    
    -- NEU: Variable für die Einstellungen
    v_settings RECORD;
BEGIN
    -- NEU: Einstellungen laden
    SELECT * INTO v_settings FROM public.game_settings WHERE id = 1;
    
    -- Fallback, falls die Einstellungen (warum auch immer) fehlen
    IF v_settings IS NULL THEN
        v_calc_mw := 1000000; 
    ELSE
        v_calc_mw := v_settings.mw_base_value;
    END IF;

    -- ==========================================
    -- 1. POSITION ERMITTELN
    -- ==========================================
    IF p_formation IS NOT NULL AND p_lineup_index IS NOT NULL AND p_lineup_index <= 10 THEN
        v_final_position := public.get_position_from_formation(p_formation, p_lineup_index);
    END IF;

    IF v_final_position IS NULL OR v_final_position IN ('N/A', 'SUB', 'N/V') THEN
        v_final_position := CASE 
            WHEN p_api_position = 'G' THEN 'TW'
            WHEN p_api_position = 'D' THEN 'IV'
            WHEN p_api_position = 'M' THEN 'ZM'
            WHEN p_api_position = 'F' THEN 'ST'
            ELSE 'SUB'
        END;
    END IF;

    -- ==========================================
    -- 2. MARKTWERT BERECHNEN (Mit Variablen!)
    -- ==========================================
    IF array_length(p_ratings, 1) > 0 THEN
        FOREACH v_rating IN ARRAY p_ratings
        LOOP
            IF v_rating IS NOT NULL THEN
                v_points_sum := v_points_sum + ROUND((v_rating - 6.0) * 100);
                v_points_count := v_points_count + 1;
            END IF;
        END LOOP;

        IF v_points_count > 0 THEN
            v_avg_points := v_points_sum / v_points_count;
            
            IF v_avg_points > 0 AND v_settings IS NOT NULL THEN
                -- NEU: Die Formel greift komplett auf die Einstellungen zu!
                v_calc_mw := ROUND(v_settings.mw_multiplier * power(v_avg_points, v_settings.mw_exponent) + v_settings.mw_base_value);
            END IF;
        END IF;
    END IF;

    -- ==========================================
    -- 3. DATENBANK UPDATES
    -- ==========================================
    UPDATE public.spieler
    SET position = CASE 
        WHEN position IS NULL OR position IN ('', 'SUB', 'N/A', 'N/V') THEN v_final_position
        WHEN v_final_position NOT IN ('SUB', 'N/A', 'N/V') AND position NOT LIKE '%' || v_final_position || '%' THEN position || ', ' || v_final_position
        ELSE position
    END
    WHERE id = p_player_id;

    UPDATE public.spieler_analytics
    SET marktwert = v_calc_mw,
        calculated_marktwert = v_calc_mw,
        last_updated_at = now()
    WHERE spieler_id = p_player_id;

END;
$function$;

