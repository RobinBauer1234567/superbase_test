CREATE OR REPLACE FUNCTION public.get_next_sync_task(p_user_id uuid)
 RETURNS SETOF sync_tasks
 LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH next_task AS (
        SELECT id 
        FROM public.sync_tasks
        WHERE status = 'PENDING'
           OR (status = 'PROCESSING' AND locked_at < now() - interval '10 minutes')
        ORDER BY priority ASC, created_at ASC
        FOR UPDATE SKIP LOCKED
        LIMIT 1
    )
    UPDATE public.sync_tasks t
    SET status = 'PROCESSING', 
        locked_at = now(),
        locked_by = p_user_id
    FROM next_task
    WHERE t.id = next_task.id
    RETURNING t.*;
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_pending_updates(p_season_id bigint)
 RETURNS TABLE(id bigint, heimteam_id bigint, "auswärtsteam_id" bigint)
 LANGUAGE plpgsql
AS $function$BEGIN
    RETURN QUERY
    SELECT s.id::bigint, s.heimteam_id::bigint, s.auswärtsteam_id::bigint
    FROM spiel s
    WHERE s.season_id = p_season_id
      AND s.status <> 'final' -- Nur Spiele, die noch nicht final sind
      AND (
          -- Fall A: LIVE-SPIELE (Hohe Priorität)
          -- Spiel läuft und Update ist älter als 5 Minuten
          (s.status = 'läuft' AND s.last_updated_at < (now() - interval '5 minutes'))
          
          OR
          
          -- Fall B: ÜBERFÄLLIGE ANPFIFFE (Der Fix für dein Problem!)
          -- Status ist 'nicht gestartet', aber Anpfiff war schon.
          -- Wir prüfen das, wenn das letzte Update länger als 60 Minuten her ist.
          -- Das fängt auch Spiele von gestern oder letzter Woche ab.
          (s.status = 'nicht gestartet' AND s.datum <= now() AND s.last_updated_at < (now() - interval '60 minutes'))
          
          OR
          
          -- Fall C: NACHKONTROLLE
          -- Spiel ist 'beendet', aber noch nicht 'final'. Wir prüfen alle 30 Min.
          (s.status = 'beendet' AND s.last_updated_at < (now() - interval '30 minutes'))
          
          OR 
          
          -- Fall D: SICHERHEITSNETZ (Besenwagen)
          -- Irgendein Spiel (außer 'final'), das seit über 12 Stunden nicht angefasst wurde.
          -- Das korrigiert alles, was durch andere Raster fällt.
          (s.last_updated_at < (now() - interval '12 hours'))
      )
    ORDER BY s.datum ASC -- Älteste Spiele zuerst fixen!
    LIMIT 15;
END;$function$;

CREATE OR REPLACE FUNCTION public.get_position_from_formation(p_formation text, p_index integer)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE
AS $function$
DECLARE
    parts int[];
    defenders int;
    attackers int;
    midfielders int[];
    mf_length int;
    midfield_sum int := 0;
    
    defense_end_index int;
    midfield_end_index int;
    attacker_end_index int;
    
    pos_index int;
    i int;
BEGIN
    -- 1. Torwart und Ersatzspieler
    IF p_index = 0 THEN RETURN 'TW'; END IF;
    IF p_index > 10 THEN RETURN 'SUB'; END IF;
    IF p_formation = 'N/A' OR p_formation IS NULL THEN RETURN 'N/A'; END IF;

    -- 2. Formation parsen (z.B. "4-2-3-1" -> {4,2,3,1})
    BEGIN
        parts := string_to_array(p_formation, '-')::int[];
    EXCEPTION WHEN OTHERS THEN
        RETURN 'N/A';
    END;
    
    IF array_length(parts, 1) < 2 OR parts IS NULL THEN
        RETURN 'N/A';
    END IF;
    
    -- Struktur aufbauen
    defenders := parts[1];
    attackers := parts[array_length(parts, 1)];
    
    -- Mittelfeld extrahieren (alles zwischen Abwehr und Sturm)
    mf_length := array_length(parts, 1) - 2;
    midfielders := ARRAY[]::int[];
    
    IF mf_length > 0 THEN
        FOR i IN 2 .. (array_length(parts, 1) - 1) LOOP
            midfielders := array_append(midfielders, parts[i]);
            midfield_sum := midfield_sum + parts[i];
        END LOOP;
    END IF;

    -- ==========================================
    -- 3. ABWEHR
    -- ==========================================
    defense_end_index := defenders;
    IF p_index > 0 AND p_index <= defense_end_index THEN
        pos_index := p_index;
        IF defenders = 3 THEN RETURN 'IV'; END IF;
        IF defenders = 4 THEN
            IF pos_index = 1 THEN RETURN 'RV'; END IF;
            IF pos_index = 4 THEN RETURN 'LV'; END IF;
            RETURN 'IV';
        END IF;
        IF defenders = 5 THEN
            IF pos_index = 1 THEN RETURN 'RV'; END IF;
            IF pos_index = 5 THEN RETURN 'LV'; END IF;
            RETURN 'IV';
        END IF;
        RETURN 'IV'; -- Fallback für andere Abwehrreihen
    END IF;

    -- ==========================================
    -- 4. MITTELFELD
    -- ==========================================
    midfield_end_index := defense_end_index + midfield_sum;
    IF p_index > defense_end_index AND p_index <= midfield_end_index THEN
        pos_index := p_index - defense_end_index;
        
        -- Fall A: Nur eine Mittelfeld-Reihe (z.B. 4-4-2)
        IF mf_length = 1 THEN
            IF midfielders[1] > 3 THEN
                IF pos_index = 1 THEN RETURN 'RA'; END IF;
                IF pos_index = midfielders[1] THEN RETURN 'LA'; END IF;
            END IF;
            RETURN 'ZM';
        END IF;

        -- Fall B: Erste Mittelfeld-Reihe (z.B. die 2 im 4-2-3-1)
        IF pos_index <= midfielders[1] THEN
            IF midfielders[1] >= 3 THEN
                IF pos_index = 1 THEN RETURN 'RV'; END IF;
                IF pos_index = midfielders[1] THEN RETURN 'LV'; END IF;
            END IF;
            IF midfielders[1] = 3 THEN RETURN 'ZM'; END IF;
            RETURN 'ZDM';
        END IF;

        -- Fall C: Zweite Mittelfeld-Reihe (z.B. die 3 im 4-2-3-1)
        IF mf_length >= 2 THEN
            IF pos_index <= (midfielders[1] + midfielders[2]) THEN
                IF midfielders[2] >= 3 THEN
                    IF pos_index = (midfielders[1] + 1) THEN RETURN 'RA'; END IF;
                    IF pos_index = (midfielders[1] + midfielders[2]) THEN RETURN 'LA'; END IF;
                    IF midfielders[2] = 3 THEN RETURN 'ZOM'; END IF;
                    RETURN 'ZM';
                END IF;
                IF mf_length >= 3 THEN RETURN 'ZM'; END IF;
                RETURN 'ZOM';
            END IF;
        END IF;

        -- Fall D: Dritte Mittelfeld-Reihe (z.B. extrem tiefe Formationen)
        IF mf_length >= 3 THEN
            IF pos_index <= (midfielders[1] + midfielders[2] + midfielders[3]) THEN
                RETURN 'ZOM';
            END IF;
        END IF;

        RETURN 'M'; -- Fallback für komplexes Mittelfeld
    END IF;

    -- ==========================================
    -- 5. STURM
    -- ==========================================
    attacker_end_index := midfield_end_index + attackers;
    IF p_index > midfield_end_index AND p_index <= attacker_end_index THEN
        pos_index := p_index - midfield_end_index;
        IF attackers <= 2 THEN RETURN 'ST'; END IF;
        IF attackers = 3 THEN
            IF pos_index = 1 THEN RETURN 'RA'; END IF;
            IF pos_index = 3 THEN RETURN 'LA'; END IF;
            RETURN 'ST';
        END IF;
    END IF;

    -- 6. FALLBACK
    RETURN 'SUB';
END;
$function$;

