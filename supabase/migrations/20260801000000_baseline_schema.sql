CREATE OR REPLACE FUNCTION public.update_spieltag_status()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_total integer;
    v_final integer;
    v_nicht_gestartet integer;
    v_new_status text;
BEGIN
    -- 1. Wir zählen die Status aller Spiele für diesen spezifischen Spieltag
    -- HIER KORRIGIERT: "round = NEW.round"
    SELECT 
        COUNT(*),
        COUNT(*) FILTER (WHERE status = 'final'),
        COUNT(*) FILTER (WHERE status = 'nicht gestartet' OR status = 'verschoben' OR status = 'canceled')
    INTO 
        v_total, 
        v_final, 
        v_nicht_gestartet
    FROM public.spiel
    WHERE round = NEW.round AND season_id = NEW.season_id;

    -- 2. Sicherheitssperre, falls keine Spiele gefunden wurden
    IF v_total = 0 THEN
        RETURN NEW;
    END IF;

    -- 3. Deine Logik-Regeln anwenden
    IF v_final = v_total THEN
        v_new_status := 'final';
    ELSIF v_nicht_gestartet = v_total THEN
        v_new_status := 'nicht gestartet';
    ELSE
        v_new_status := 'läuft';
    END IF;

    -- 4. Den Status in der Spieltag-Tabelle aktualisieren
    -- HIER KORRIGIERT: "round = NEW.round"
    UPDATE public.spieltag
    SET status = v_new_status
    WHERE round = NEW.round AND season_id = NEW.season_id;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_spieltag_zeitfenster()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
    -- Update den Spieltag mit den berechneten Zeiten aus der Tabelle 'spiel'
    UPDATE public.spieltag
    SET 
        -- 48 Stunden VOR dem allerersten Spiel dieses Spieltags
        matchday_start = (
            SELECT MIN(datum) - INTERVAL '48 hours'
            FROM public.spiel
            WHERE round = NEW.round AND season_id = NEW.season_id
        ),
        -- 24 Stunden NACH dem allerletzten Spiel dieses Spieltags
        matchday_end = (
            SELECT MAX(datum) + INTERVAL '24 hours'
            FROM public.spiel
            WHERE round = NEW.round AND season_id = NEW.season_id
        )
    WHERE round = NEW.round AND season_id = NEW.season_id;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_team_analytics(p_team_id bigint, p_season_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    -- (Dein bisheriger DECLARE-Block bleibt hier unverändert)
    v_matches RECORD;
    v_points int := 0;
    v_goals_for int := 0;
    v_goals_against int := 0;
    v_match_count int := 0;
    v_form_points int := 0;
    v_form_match_count int := 0;
    v_score_home int;
    v_score_away int;
    v_is_home boolean;
    v_calc_strength numeric;
    v_calc_form numeric;
BEGIN
    FOR v_matches IN 
        SELECT heimteam_id, auswärtsteam_id, ergebnis FROM public.spiel 
        WHERE season_id = p_season_id AND status = 'final' AND (heimteam_id = p_team_id OR auswärtsteam_id = p_team_id) ORDER BY datum DESC
    LOOP
        BEGIN
            v_score_home := split_part(v_matches.ergebnis, ':', 1)::int;
            v_score_away := split_part(v_matches.ergebnis, ':', 2)::int;
        EXCEPTION WHEN OTHERS THEN CONTINUE; END;
        v_is_home := (v_matches.heimteam_id = p_team_id);
        v_match_count := v_match_count + 1;
        IF v_is_home THEN
            v_goals_for := v_goals_for + v_score_home; v_goals_against := v_goals_against + v_score_away;
        ELSE
            v_goals_for := v_goals_for + v_score_away; v_goals_against := v_goals_against + v_score_home;
        END IF;
        IF (v_is_home AND v_score_home > v_score_away) OR (NOT v_is_home AND v_score_away > v_score_home) THEN
            v_points := v_points + 3; IF v_match_count <= 5 THEN v_form_points := v_form_points + 3; END IF;
        ELSIF v_score_home = v_score_away THEN
            v_points := v_points + 1; IF v_match_count <= 5 THEN v_form_points := v_form_points + 1; END IF;
        END IF;
        IF v_match_count <= 5 THEN v_form_match_count := v_form_match_count + 1; END IF;
    END LOOP;

    IF v_form_match_count > 0 THEN v_calc_form := ROUND((v_form_points::numeric / v_form_match_count::numeric), 2); ELSE v_calc_form := 0.00; END IF;

    IF v_match_count > 0 THEN
        v_calc_strength := (v_points::numeric / v_match_count::numeric) * 2.5 + ((v_goals_for - v_goals_against)::numeric / v_match_count::numeric) * 0.5 + 2.5;
        v_calc_strength := ROUND(LEAST(GREATEST(v_calc_strength, 1.0), 10.0), 2);
    ELSE
        v_calc_strength := 5.00;
    END IF;

    -- ==========================================
    -- GEFIXT: UPSERT STATT UPDATE
    -- ==========================================
    INSERT INTO public.team_analytics (team_id, gesamtstaerke, form, last_updated_at)
    VALUES (p_team_id, v_calc_strength, v_calc_form, now())
    ON CONFLICT (team_id) DO UPDATE 
    SET gesamtstaerke = EXCLUDED.gesamtstaerke,
        form = EXCLUDED.form,
        last_updated_at = now();
END;
$function$;


