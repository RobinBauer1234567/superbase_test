CREATE OR REPLACE FUNCTION public.update_gesamtstatistiken()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  v_mr_id bigint;
  player_id bigint;
  _season_id bigint;
  _stats_sum jsonb := '{}'::jsonb;
  aggregated_stats jsonb;
  total_punkte numeric := 0;
  total_matches bigint := 0;
begin
  v_mr_id := coalesce(
    (case when new is not null then (new.id)::bigint end),
    (case when old is not null then (old.id)::bigint end)
  );

  if v_mr_id is null then return null; end if;

  select mr.spieler_id::bigint, sp.season_id::bigint
  into player_id, _season_id
  from matchrating mr
  join spiel sp on sp.id = mr.spiel_id
  where mr.id = v_mr_id
  limit 1;

  if player_id is null or _season_id is null then return null; end if;

  select coalesce(jsonb_object_agg(key, val_sum), '{}'::jsonb)
  into _stats_sum
  from (
    select e.key,
      sum(
        case jsonb_typeof(e.val)
          when 'number' then (e.val)::text::numeric
          when 'object' then coalesce(
            nullif(regexp_replace(e.val->>'original','[^0-9\.-]+','','g'),'')::numeric,
            nullif(regexp_replace(e.val->>'alternative','[^0-9\.-]+','','g'),'')::numeric,
            nullif(regexp_replace(e.val->>'value','[^0-9\.-]+','','g'),'')::numeric,
            0
          )
          when 'string' then coalesce(nullif(regexp_replace(e.val::text,'[^0-9\.-]+','','g'), '')::numeric, 0)
          else 0
        end
      ) as val_sum
    from matchrating mr
    join spiel sp on sp.id = mr.spiel_id
    cross join lateral jsonb_each(coalesce(mr.statistics, '{}'::jsonb)) as e(key, val)
    where mr.spieler_id = player_id and sp.season_id = _season_id
    group by e.key
  ) sub;

  select coalesce(sum(mr.punkte)::numeric, 0), coalesce(count(*)::bigint, 0)
  into total_punkte, total_matches
  from matchrating mr
  join spiel sp on sp.id = mr.spiel_id
  where mr.spieler_id = player_id and sp.season_id = _season_id;

  if total_matches = 0 then
    update public.spieler_analytics
    set gesamtstatistiken = '{}'::jsonb, anzahl_spiele = 0
    where spieler_id = player_id and season_id = _season_id;
    return null;
  end if;

  aggregated_stats := coalesce(_stats_sum, '{}'::jsonb)
    || jsonb_build_object('gesamtpunkte', total_punkte);

  -- HIER IST DER FIX: marktwert & calculated_marktwert (1000000) wurden zum INSERT hinzugefügt!
  INSERT INTO public.spieler_analytics (spieler_id, season_id, gesamtstatistiken, anzahl_spiele, marktwert, calculated_marktwert)
  VALUES (player_id, _season_id, aggregated_stats, total_matches, 1000000, 1000000)
  ON CONFLICT (spieler_id, season_id) 
  DO UPDATE SET 
    gesamtstatistiken = aggregated_stats,
    anzahl_spiele = total_matches;

  return null;
end;
$function$;

CREATE OR REPLACE FUNCTION public.update_matchup_faktor(p_team_id bigint, p_season_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    -- (Dein bisheriger DECLARE-Block bleibt hier unverändert)
    v_own_strength numeric;
    v_opp_strength numeric;
    v_matchup_val numeric;
    v_total_factor numeric := 0;
    v_game_count int := 0;
    v_weights numeric[] := ARRAY[0.50, 0.35, 0.15];
    v_weight_sum numeric := 0;
    v_game RECORD;
BEGIN
    SELECT gesamtstaerke INTO v_own_strength FROM public.team_analytics WHERE team_id = p_team_id;
    IF v_own_strength IS NULL THEN v_own_strength := 5.0; END IF;

    FOR v_game IN 
        SELECT heimteam_id, auswärtsteam_id FROM public.spiel 
        WHERE season_id = p_season_id AND status = 'nicht gestartet' AND (heimteam_id = p_team_id OR auswärtsteam_id = p_team_id) ORDER BY datum ASC LIMIT 3
    LOOP
        v_game_count := v_game_count + 1;
        IF v_game.heimteam_id = p_team_id THEN
            SELECT gesamtstaerke INTO v_opp_strength FROM public.team_analytics WHERE team_id = v_game.auswärtsteam_id;
        ELSE
            SELECT gesamtstaerke INTO v_opp_strength FROM public.team_analytics WHERE team_id = v_game.heimteam_id;
        END IF;
        IF v_opp_strength IS NULL OR v_opp_strength = 0 THEN v_opp_strength := 5.0; END IF;
        
        v_matchup_val := GREATEST(0.5, LEAST(1.5, (v_own_strength / v_opp_strength)));
        v_total_factor := v_total_factor + (v_matchup_val * v_weights[v_game_count]);
        v_weight_sum := v_weight_sum + v_weights[v_game_count];
    END LOOP;

    IF v_weight_sum < 1.0 THEN v_total_factor := v_total_factor + ((1.0 - v_weight_sum) * 1.0); END IF;
    IF v_game_count = 0 THEN v_total_factor := 1.0; END IF;

    -- ==========================================
    -- GEFIXT: UPSERT STATT UPDATE
    -- ==========================================
    INSERT INTO public.team_analytics (team_id, matchup_faktor)
    VALUES (p_team_id, ROUND(v_total_factor, 2))
    ON CONFLICT (team_id) DO UPDATE 
    SET matchup_faktor = EXCLUDED.matchup_faktor;
END;
$function$;

CREATE OR REPLACE FUNCTION public.update_spieler_analytics_prognose(p_spieler_id bigint, p_season_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_team_id bigint;
    v_matchup_faktor numeric;
    v_punkteschnitt numeric := 0;
    v_form numeric := 0;
    v_startelf_quote numeric := 0;
    v_expected_points numeric := 0;
BEGIN
    -- 1. Aktuelles Team des Spielers herausfinden (FIX: is_active = true hinzugefügt)
    SELECT team_id INTO v_team_id 
    FROM public.season_players 
    WHERE player_id = p_spieler_id 
      AND season_id = p_season_id 
      AND is_active = true
    LIMIT 1;

    IF v_team_id IS NULL THEN RETURN; END IF;

    -- 2. Matchup-Faktor
    SELECT COALESCE(matchup_faktor, 1.0) INTO v_matchup_faktor 
    FROM public.team_analytics 
    WHERE team_id = v_team_id;

    -- 3. Punkteschnitt
    SELECT COALESCE(AVG(punkte), 0) INTO v_punkteschnitt
    FROM public.matchrating mr
    JOIN public.spiel s ON mr.spiel_id = s.id
    WHERE mr.spieler_id = p_spieler_id AND s.season_id = p_season_id;

    -- 4. Form und Startelf-Quote
    SELECT 
        COALESCE(AVG(mr.punkte), 0),
        COALESCE(COUNT(mr.id) FILTER (WHERE mr.formationsindex <= 10)::numeric / GREATEST(COUNT(last_games.id), 1), 0)
    INTO v_form, v_startelf_quote
    FROM (
        SELECT id 
        FROM public.spiel 
        WHERE season_id = p_season_id 
          AND status = 'final'
          AND (heimteam_id = v_team_id OR auswärtsteam_id = v_team_id)
        ORDER BY datum DESC
        LIMIT 5
    ) as last_games
    LEFT JOIN public.matchrating mr ON mr.spiel_id = last_games.id AND mr.spieler_id = p_spieler_id;

    -- 5. Expected Points berechnen
    v_expected_points := ((v_punkteschnitt * 0.4) + (v_form * 0.6)) * v_matchup_faktor * v_startelf_quote;
    v_expected_points := GREATEST(0, ROUND(v_expected_points, 2));

    -- 6. Daten in spieler_analytics speichern
    UPDATE public.spieler_analytics
    SET punkteschnitt = ROUND(v_punkteschnitt, 2),
        form = ROUND(v_form, 2),
        startelf_quote = ROUND(v_startelf_quote, 2),
        expected_points = v_expected_points,
        last_updated_at = now()
    WHERE spieler_id = p_spieler_id AND season_id = p_season_id;
END;
$function$;

