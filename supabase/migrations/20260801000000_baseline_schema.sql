CREATE OR REPLACE FUNCTION public.freeze_late_transfers()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_point_record RECORD;
    v_spiel_id bigint;
    v_spiel_status text;
    v_is_locked boolean;
    v_mr_id bigint;
    v_punkte int;
BEGIN
    -- 1. Nur ausführen, wenn wir eine gültige user_id haben (z.B. nicht beim Verkauf an das System)
    IF NEW.user_id IS NULL THEN 
        RETURN NEW; 
    END IF;

    -- 2. Finde alle existierenden Snapshots (user_matchday_points) dieses Users,
    --    deren zugehöriger Spieltag noch nicht 'final' ist.
    FOR v_point_record IN 
        SELECT ump.id, ump.round, ump.season_id, ump.is_locked AS header_locked
        FROM public.user_matchday_points ump
        JOIN public.spieltag st ON st.season_id = ump.season_id AND st.round = ump.round
        WHERE ump.user_id = NEW.user_id 
          AND ump.league_id = NEW.league_id 
          AND st.status != 'final'
    LOOP
        -- 3. Suche das spezifische Spiel des gekauften Spielers an genau diesem Spieltag
        v_spiel_id := NULL;
        v_spiel_status := 'nicht gestartet';
        v_mr_id := NULL;
        v_punkte := 0;

        SELECT s.id, LOWER(s.status), mr.id, mr.punkte
        INTO v_spiel_id, v_spiel_status, v_mr_id, v_punkte
        FROM public.season_players sp
        JOIN public.spiel s ON (s.heimteam_id = sp.team_id OR s.auswärtsteam_id = sp.team_id)
            AND s.season_id = v_point_record.season_id 
            AND s.round = v_point_record.round
        LEFT JOIN public.matchrating mr ON mr.spiel_id = s.id AND mr.spieler_id = NEW.player_id
        WHERE sp.player_id = NEW.player_id 
          AND sp.season_id = v_point_record.season_id
        LIMIT 1;

        -- 4. Lock-Status bestimmen: Wenn das Spiel schon angepfiffen ist oder war, wird gesperrt!
        IF v_spiel_status IN ('läuft', 'beendet', 'final') THEN
            v_is_locked := true;
            
            -- NEU: Wenn der Spieler gelockt wird, MUSS auch der gesamte Spieltag gelockt werden!
            -- Wir prüfen vorher, ob er nicht ohnehin schon gelockt ist, um unnötige DB-Updates zu vermeiden.
            IF NOT v_point_record.header_locked THEN
                UPDATE public.user_matchday_points
                SET is_locked = true
                WHERE id = v_point_record.id;
            END IF;
            
        ELSE
            v_is_locked := false;
        END IF;

        -- 5. Spieler in den Matchday Snapshot einfügen (auf die Bank: Index 99)
        IF NOT EXISTS (SELECT 1 FROM public.user_matchday_players WHERE matchday_point_id = v_point_record.id AND player_id = NEW.player_id) THEN
            INSERT INTO public.user_matchday_players (
                matchday_point_id, 
                player_id, 
                formation_index, 
                is_locked, 
                spiel_id, 
                matchrating_id, 
                points
            ) VALUES (
                v_point_record.id, 
                NEW.player_id, 
                99, -- Bank
                v_is_locked, 
                v_spiel_id, 
                v_mr_id, 
                COALESCE(v_punkte, 0)
            );
        END IF;

    END LOOP;

    RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.generate_daily_transfers(p_league_id bigint, p_season_id bigint, p_amount integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  player_rec RECORD;
  v_random_hours numeric;
BEGIN
  FOR player_rec IN
    SELECT s.id, sa.marktwert 
    FROM public.spieler s
    -- NEU: Filter beim JOIN auf die Saison!
    JOIN public.spieler_analytics sa ON sa.spieler_id = s.id AND sa.season_id = p_season_id
    WHERE 
    EXISTS (SELECT 1 FROM public.season_players sp WHERE sp.player_id = s.id AND sp.season_id = p_season_id)
    AND NOT EXISTS (SELECT 1 FROM public.league_players lp WHERE lp.player_id = s.id AND lp.league_id = p_league_id)
    AND NOT EXISTS (SELECT 1 FROM public.transfer_market tm WHERE tm.player_id = s.id AND tm.league_id = p_league_id AND tm.is_active = true)
    AND sa.marktwert IS NOT NULL AND sa.marktwert > 0
    ORDER BY random()
    LIMIT p_amount
  LOOP
    v_random_hours := 24 + (random() * 48);

    INSERT INTO public.transfer_market (
      league_id, player_id, seller_id, listed_at, expires_at, min_bid_price, buy_now_price, is_active
    )
    VALUES (
      p_league_id, player_rec.id, NULL, now(), now() + (v_random_hours * interval '1 hour'), 
      player_rec.marktwert, player_rec.marktwert + 3000000, true
    );
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.generate_routine_sync_tasks()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
BEGIN
    -- --------------------------------------------------------------------------
    -- 1. MATCH UPDATES (Live-Spiele - Prio 1 oder 7)
    -- --------------------------------------------------------------------------
    INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, match_id, priority, status)
    SELECT 
        'UPDATE_MATCH', s.tournament_id, sp.season_id, sp.id,
        CASE WHEN sp.datum >= now() - interval '6 hours' THEN 1 ELSE 7 END,
        'PENDING'
    FROM public.spiel sp
    JOIN public.season s ON sp.season_id = s.id
    WHERE sp.status != 'final' 
      AND sp.datum <= now() 
      AND s.is_active = true
      AND s.is_initialized = true  -- NEU: Sicherer Schutz!
      AND NOT EXISTS (
          SELECT 1 FROM public.sync_tasks st 
          WHERE st.task_type = 'UPDATE_MATCH' AND st.match_id = sp.id AND st.status IN ('PENDING', 'PROCESSING', 'WAITING')
      );

    -- --------------------------------------------------------------------------
    -- 2. SPIELPLAN UPDATES (Prio 5)
    -- --------------------------------------------------------------------------
    INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, priority, status)
    SELECT 'UPDATE_SCHEDULE', s.tournament_id, s.id, 5, 'PENDING'
    FROM public.season s
    WHERE s.is_active = true
      AND s.is_initialized = true  -- NEU: Sicherer Schutz!
      AND NOT EXISTS (
          SELECT 1 FROM public.sync_tasks st 
          WHERE st.task_type = 'UPDATE_SCHEDULE' AND st.season_id = s.id AND st.created_at > now() - interval '24 hours'
      );

    -- --------------------------------------------------------------------------
    -- 3. TRANSFER UPDATES (Prio 8)
    -- --------------------------------------------------------------------------
    INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, priority, status)
    SELECT 'SYNC_TRANSFERS', s.tournament_id, s.id, 8, 'PENDING'
    FROM public.season s
    WHERE s.is_active = true
      AND s.is_initialized = true  -- NEU: Sicherer Schutz!
      AND NOT EXISTS (
          SELECT 1 FROM public.sync_tasks st 
          WHERE st.task_type = 'SYNC_TRANSFERS' AND st.season_id = s.id AND st.created_at > now() - interval '12 hours'
      );

    -- --------------------------------------------------------------------------
    -- 4. SPIELER REPARIEREN (Prio 9)
    -- --------------------------------------------------------------------------
    INSERT INTO public.sync_tasks (task_type, tournament_id, season_id, priority, status)
    SELECT 'REPAIR_PLAYERS', s.tournament_id, s.id, 9, 'PENDING'
    FROM public.season s
    WHERE s.is_active = true
      AND s.is_initialized = true  -- NEU: Sicherer Schutz!
      AND NOT EXISTS (
          SELECT 1 FROM public.sync_tasks st 
          WHERE st.task_type = 'REPAIR_PLAYERS' AND st.season_id = s.id AND st.created_at > now() - interval '6 hours'
      );
END;
$function$;

