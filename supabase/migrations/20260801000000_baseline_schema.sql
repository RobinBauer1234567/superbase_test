CREATE OR REPLACE FUNCTION public.process_expired_transfers()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  t_rec RECORD; bid_rec RECORD; v_winner_budget numeric; v_player RECORD;
  v_season_id bigint; v_seller_name text; v_seller_avatar text;
  v_buyer_name text; v_buyer_avatar text; v_is_system_buy boolean;
  v_final_price bigint; v_failed_bid boolean; v_transfer_type text; v_winner_found boolean;
BEGIN
  PERFORM set_config('my.skip_trigger', 'true', true);

  FOR t_rec IN SELECT * FROM transfer_market WHERE is_active = true AND expires_at <= now() LOOP
    v_seller_name := 'System'; v_seller_avatar := NULL; v_buyer_name := 'System'; v_buyer_avatar := NULL; 
    v_is_system_buy := true; v_failed_bid := false; v_transfer_type := 'AUKTION'; v_winner_found := false;

    SELECT season_id INTO v_season_id FROM leagues WHERE id = t_rec.league_id;
    
    -- JOIN über season_players statt spieler.team_id
    SELECT s.name, s.position, s.profilbild_url, t.image_url AS team_image_url, sa.marktwert, sa.punkteschnitt 
    INTO v_player FROM spieler s 
    LEFT JOIN season_players sp ON sp.player_id = s.id AND sp.season_id = v_season_id AND sp.is_active = true
    LEFT JOIN team t ON sp.team_id = t.id 
    LEFT JOIN spieler_analytics sa ON sa.spieler_id = s.id AND sa.season_id = v_season_id 
    WHERE s.id = t_rec.player_id;

    IF t_rec.seller_id IS NOT NULL THEN SELECT username, avatar_url INTO v_seller_name, v_seller_avatar FROM profiles WHERE user_id = t_rec.seller_id; END IF;

    FOR bid_rec IN SELECT * FROM transfer_bids WHERE transfer_id = t_rec.id ORDER BY amount DESC LOOP
      SELECT budget INTO v_winner_budget FROM league_members WHERE league_id = t_rec.league_id AND user_id = bid_rec.bidder_id;
      IF v_winner_budget >= bid_rec.amount THEN
        v_winner_found := true; v_final_price := bid_rec.amount; v_is_system_buy := false;
        SELECT username, avatar_url INTO v_buyer_name, v_buyer_avatar FROM profiles WHERE user_id = bid_rec.bidder_id;
        UPDATE league_members SET budget = budget - bid_rec.amount WHERE league_id = t_rec.league_id AND user_id = bid_rec.bidder_id;
        IF t_rec.seller_id IS NOT NULL THEN UPDATE league_members SET budget = budget + bid_rec.amount WHERE league_id = t_rec.league_id AND user_id = t_rec.seller_id; END IF;
        INSERT INTO league_players (league_id, user_id, player_id, purchase_price) VALUES (t_rec.league_id, bid_rec.bidder_id, t_rec.player_id, bid_rec.amount);
        EXIT;
      ELSE v_failed_bid := true; END IF;
    END LOOP;

    IF NOT v_winner_found THEN
        IF EXISTS (SELECT 1 FROM transfer_bids WHERE transfer_id = t_rec.id) THEN v_transfer_type := 'AUKTION'; ELSE v_transfer_type := 'KEINE GEBOTE'; END IF;
        v_final_price := t_rec.min_bid_price;
        IF t_rec.seller_id IS NOT NULL THEN UPDATE league_members SET budget = budget + t_rec.min_bid_price WHERE league_id = t_rec.league_id AND user_id = t_rec.seller_id; END IF;
    END IF;

    INSERT INTO league_activities (league_id, type, content) VALUES (t_rec.league_id, 'TRANSFER', jsonb_build_object(
        'transfer_type', v_transfer_type, 'transfer_id', t_rec.id, 'player_id', t_rec.player_id, 'position', v_player.position, 'player_name', v_player.name,
        'profilbild_url', v_player.profilbild_url, 'team_image_url', v_player.team_image_url, 'marktwert', v_player.marktwert, 'score', ROUND(COALESCE(v_player.punkteschnitt, 0)),
        'buyer_name', v_buyer_name, 'buyer_avatar_url', v_buyer_avatar, 'seller_name', v_seller_name, 'seller_avatar_url', v_seller_avatar, 'price', v_final_price, 'is_system_buy', v_is_system_buy, 'failed_highest_bid', v_failed_bid
    ));
    UPDATE transfer_market SET is_active = false WHERE id = t_rec.id;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.process_match_lineups(p_spiel_id bigint, p_season_id bigint, p_raw_json jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_home_formation text; v_away_formation text; v_home_id int; v_away_id int;
    v_team_type text; v_team_id int; v_formation text; v_idx int; player_item jsonb;
    v_player_id int; v_player_name text; v_api_pos text; v_calc_pos text;
    v_rating numeric; v_stats jsonb; v_fantasy_points int; v_match_rating_id bigint;
BEGIN
    INSERT INTO public.api_debug_dump (spiel_id, raw_json) VALUES (p_spiel_id, p_raw_json);
    SELECT heimteam_id, auswärtsteam_id INTO v_home_id, v_away_id FROM spiel WHERE id = p_spiel_id;
    
    v_home_formation := p_raw_json->'home'->>'formation';
    v_away_formation := p_raw_json->'away'->>'formation';

    -- SICHERHEIT: ON CONFLICT (formation) explizit gemacht
    IF v_home_formation IS NOT NULL AND v_home_formation <> 'N/A' THEN
        INSERT INTO formation (formation, positionsliste) VALUES (v_home_formation, public.calculate_formation_array(v_home_formation)) 
        ON CONFLICT (formation) DO NOTHING;
    END IF;
    IF v_away_formation IS NOT NULL AND v_away_formation <> 'N/A' THEN
        INSERT INTO formation (formation, positionsliste) VALUES (v_away_formation, public.calculate_formation_array(v_away_formation)) 
        ON CONFLICT (formation) DO NOTHING;
    END IF;

    UPDATE spiel SET hometeam_formation = v_home_formation, awayteam_formation = v_away_formation, last_updated_at = now() WHERE id = p_spiel_id;

    FOREACH v_team_type IN ARRAY ARRAY['home', 'away'] LOOP
        IF v_team_type = 'home' THEN v_team_id := v_home_id; v_formation := v_home_formation;
        ELSE v_team_id := v_away_id; v_formation := v_away_formation; END IF;

        v_idx := 0;
        FOR player_item IN SELECT * FROM jsonb_array_elements(p_raw_json->v_team_type->'players') LOOP
            v_player_id := (player_item->'player'->>'id')::int;
            v_player_name := player_item->'player'->>'name';
            v_api_pos := player_item->'player'->>'position';
            v_stats := player_item->'statistics';
            v_rating := (v_stats->>'rating')::numeric;

            v_calc_pos := public.get_position_from_formation(v_formation, v_idx);
            IF v_calc_pos = 'N/A' OR v_calc_pos IS NULL THEN
                 v_calc_pos := CASE WHEN v_api_pos = 'G' THEN 'TW' WHEN v_api_pos = 'D' THEN 'IV' WHEN v_api_pos = 'M' THEN 'ZM' WHEN v_api_pos = 'F' THEN 'ST' ELSE 'SUB' END;
            END IF;
            v_fantasy_points := public.calculate_fantasy_points(v_api_pos, v_stats);

            INSERT INTO spieler (id, name, position) VALUES (v_player_id, v_player_name, v_calc_pos)
            ON CONFLICT (id) DO UPDATE SET position = CASE 
                    WHEN EXCLUDED.position IN ('SUB', 'N/A', 'N/V') THEN COALESCE(spieler.position, EXCLUDED.position)
                    WHEN spieler.position IS NULL OR spieler.position IN ('', 'SUB', 'N/A', 'N/V') THEN EXCLUDED.position
                    WHEN EXCLUDED.position = ANY(string_to_array(replace(spieler.position, ' ', ''), ',')) THEN spieler.position
                    ELSE spieler.position || ', ' || EXCLUDED.position
                END;

            UPDATE public.season_players SET is_active = false
            WHERE season_id = p_season_id AND player_id = v_player_id AND team_id != v_team_id AND is_active = true;

            -- HIER GREIFT NUN DER NEUE CONSTRAINT
            INSERT INTO season_players (season_id, player_id, team_id, is_active) VALUES (p_season_id, v_player_id, v_team_id, true)
            ON CONFLICT ON CONSTRAINT season_players_unique_combo DO UPDATE SET is_active = true;

            v_match_rating_id := (p_spiel_id::text || v_player_id::text)::bigint;
            INSERT INTO matchrating (id, spiel_id, spieler_id, punkte, statistics, neuepunkte, formationsindex, match_position)
            VALUES (v_match_rating_id, p_spiel_id, v_player_id, ROUND((COALESCE(v_rating, 6.0) - 6) * 100), v_stats, v_fantasy_points, v_idx, v_calc_pos)
            ON CONFLICT (id) DO UPDATE SET punkte = EXCLUDED.punkte, statistics = EXCLUDED.statistics, neuepunkte = EXCLUDED.neuepunkte, formationsindex = EXCLUDED.formationsindex, match_position = EXCLUDED.match_position;

            v_idx := v_idx + 1;
        END LOOP;
    END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.process_random_system_transfers()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_league RECORD;
    v_user_count INT;
    v_market_size INT;
    v_target_size INT;
    v_probability NUMERIC;
    v_random NUMERIC;
BEGIN
    -- 1. Schleife: Gehe durch alle AKTIVEN Ligen
    FOR v_league IN 
        SELECT id, season_id FROM public.leagues WHERE is_active = true AND season_id IS NOT NULL
    LOOP
        -- 2. Wie viele Nutzer (Manager) spielen in dieser Liga mit?
        SELECT COUNT(*) INTO v_user_count 
        FROM public.league_members 
        WHERE league_id = v_league.id;

        -- 3. Wie viele System-Spieler sind aktuell auf dem Markt?
        -- (seller_id IS NULL bedeutet, der Spieler kommt vom System)
        SELECT COUNT(*) INTO v_market_size 
        FROM public.transfer_market 
        WHERE league_id = v_league.id AND is_active = true AND seller_id IS NULL;

        -- 4. Berechne die Ziel-Größe des Transfermarkts (BALANCING)
        -- Hier eingestellt: 4 Spieler pro User, mindestens aber 10 Spieler insgesamt.
        v_target_size := GREATEST(10, v_user_count * 4);

        -- 5. Berechne die Wahrscheinlichkeit
        IF v_market_size >= v_target_size THEN
            -- Der Markt ist schon gut gefüllt. Nur 5% Chance auf einen neuen Spieler.
            v_probability := 0.05; 
        ELSE
            -- Wahrscheinlichkeit basierend auf der Lücke (Je leerer, desto höher die Chance)
            v_probability := (v_target_size - v_market_size)::NUMERIC / v_target_size::NUMERIC;
        END IF;

        -- 6. Würfeln! (Zufallszahl zwischen 0.00 und 1.00 generieren)
        v_random := random();

        -- 7. Gewonnen? Dann stelle 1 Spieler auf den Markt!
        IF v_random <= v_probability THEN
            -- Wir nutzen deine bereits vorhandene Funktion, um 1 Spieler hinzuzufügen
            PERFORM public.generate_daily_transfers(v_league.id, v_league.season_id, 1);
        END IF;

    END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.process_transfer_event(p_transfer_id bigint, p_player_id bigint, p_from_team_id bigint, p_to_team_id bigint, p_season_id integer)
 RETURNS boolean
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_exists boolean;
    v_team_exists boolean;
    v_player_exists boolean;
BEGIN
    -- 1. Prüfen, ob wir diesen Transfer schon bearbeitet haben
    SELECT EXISTS(SELECT 1 FROM processed_transfers WHERE transfer_id = p_transfer_id) INTO v_exists;
    IF v_exists THEN
        RETURN false; -- Haben wir schon, Abbruch!
    END IF;

    -- 2. NEU: Prüfen, ob der Spieler überhaupt in unserer Datenbank existiert
    SELECT EXISTS(SELECT 1 FROM spieler WHERE id = p_player_id) INTO v_player_exists;
    IF NOT v_player_exists THEN
        -- Wenn er nicht existiert, speichern wir den Transfer trotzdem als "erledigt" ab.
        -- So versuchen wir nicht bei jedem App-Start erneut, diesen Fehler zu provozieren.
        INSERT INTO processed_transfers (transfer_id) VALUES (p_transfer_id);
        RETURN false;
    END IF;

    -- 3. Alten Verein deaktivieren (Transfer Out)
    IF p_from_team_id IS NOT NULL THEN
        UPDATE public.season_players
        SET is_active = false
        WHERE player_id = p_player_id 
          AND season_id = p_season_id 
          AND team_id = p_from_team_id 
          AND is_active = true;
    END IF;

    -- 4. Neuen Verein zuweisen (Transfer In)
    IF p_to_team_id IS NOT NULL THEN
        SELECT EXISTS(SELECT 1 FROM team WHERE id = p_to_team_id) INTO v_team_exists;
        
        IF v_team_exists THEN
            INSERT INTO public.season_players (season_id, player_id, team_id, is_active)
            VALUES (p_season_id, p_player_id, p_to_team_id, true)
            ON CONFLICT ON CONSTRAINT season_players_unique_combo 
            DO UPDATE SET is_active = true;
        END IF;
    END IF;

    -- 5. Transfer als "erledigt" markieren
    INSERT INTO processed_transfers (transfer_id) VALUES (p_transfer_id);

    RETURN true;
END;
$function$;

CREATE OR REPLACE FUNCTION public.quick_sell_player(p_league_id bigint, p_player_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  v_mw integer;
  v_sell_price integer;
  v_user_id uuid;
  v_season_id bigint;
BEGIN
  v_user_id := auth.uid();

  IF NOT EXISTS (SELECT 1 FROM public.league_players WHERE league_id = p_league_id AND player_id = p_player_id AND user_id = v_user_id) THEN
