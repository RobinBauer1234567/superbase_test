CREATE OR REPLACE FUNCTION public.request_sync_permission()
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_last_sync timestamptz;
    v_timeout timestamptz;
    v_current_user uuid;
BEGIN
    v_current_user := auth.uid();

    -- Aktuellen Status holen
    SELECT last_sync_at, lock_timeout
    INTO v_last_sync, v_timeout
    FROM public.api_sync_lock
    WHERE id = 1;

    -- REGEL 1: Ist der letzte Sync weniger als 5 Minuten her? -> BLOCKIEREN
    IF v_last_sync > (now() - interval '5 minutes') THEN
        RETURN false;
    END IF;

    -- REGEL 2: Ist gerade gesperrt und Timeout noch nicht abgelaufen? -> BLOCKIEREN
    IF v_timeout > now() THEN
        RETURN false;
    END IF;

    -- GRÜNES LICHT: Wir setzen den Lock für diesen User für 2 Minuten
    UPDATE public.api_sync_lock
    SET is_locked_by = v_current_user,
        last_sync_at = now(), -- Wir setzen den Zeitstempel jetzt auf Start
        lock_timeout = now() + interval '2 minutes' -- Sicherheitsnetz falls App abstürzt
    WHERE id = 1;

    RETURN true;
END;
$function$;

