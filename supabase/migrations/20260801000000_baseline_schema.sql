CREATE OR REPLACE FUNCTION public.handle_member_activity()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_user_name text;
    v_avatar_url text;
    v_target_user_id uuid;
BEGIN
    -- ID des betroffenen Users feststellen (bei INSERT ist es NEW, bei DELETE ist es OLD)
