CREATE OR REPLACE FUNCTION public.save_lineup(p_league_id bigint, p_season_id bigint, p_round integer, p_formation text, p_updates jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  v_user_id uuid := auth.uid();
  v_point_id bigint;
  v_item JSONB;
BEGIN
  -- 1. Snapshot für diesen ausgewählten Spieltag holen oder erstellen
  SELECT id INTO v_point_id FROM public.user_matchday_points 
  WHERE user_id = v_user_id AND league_id = p_league_id AND season_id = p_season_id AND round = p_round;

  IF v_point_id IS NULL THEN
      INSERT INTO public.user_matchday_points (user_id, league_id, season_id, round, formation)
      VALUES (v_user_id, p_league_id, p_season_id, p_round, p_formation)
      RETURNING id INTO v_point_id;
  ELSE
      -- Wenn er schon da ist, updaten wir die gewählte Formation
      UPDATE public.user_matchday_points SET formation = p_formation WHERE id = v_point_id;
  END IF;

  -- ACHTUNG: Hier wurde vorher alles per DELETE gelöscht! Das machen wir nicht mehr.

  -- 2. Nur die Indizes der ungelockten Spieler aktualisieren
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_updates) 
  LOOP
    -- Prüfen, ob der Spieler für diesen Spieltag bereits im Snapshot existiert
    IF EXISTS (SELECT 1 FROM public.user_matchday_players WHERE matchday_point_id = v_point_id AND player_id = (v_item->>'player_id')::int) THEN
        
        -- UPDATE: Ändert den Index nur, wenn der Spieler NICHT gelockt ist!
        UPDATE public.user_matchday_players
        SET formation_index = (v_item->>'index')::int
        WHERE matchday_point_id = v_point_id 
          AND player_id = (v_item->>'player_id')::int
          AND is_locked = false;
          
    ELSE
        -- INSERT: Falls der Spieler noch gar nicht im Snapshot war (z.B. weil er gerade erst gekauft wurde)
        INSERT INTO public.user_matchday_players (matchday_point_id, player_id, formation_index, is_locked)
        VALUES (v_point_id, (v_item->>'player_id')::int, (v_item->>'index')::int, false);
    END IF;
    
  END LOOP;
  
  -- 3. (Optional aber empfohlen) Punkte der Startelf neu kalkulieren
  -- Falls durch den Wechsel ungelockter Spieler jemand anderes in die Startelf rückt,
  -- sollten die Gesamtpunkte im Header aktualisiert werden.
  UPDATE public.user_matchday_points
  SET total_points = (
      SELECT COALESCE(SUM(points), 0)
      FROM public.user_matchday_players
      WHERE matchday_point_id = v_point_id
        AND formation_index <= 10
  )
  WHERE id = v_point_id;

END;
$function$;

