CREATE OR REPLACE FUNCTION public.cleanup_duplicate_matches(p_season_id bigint)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
BEGIN
    -- Wir löschen jedes Spiel (s1)...
    DELETE FROM public.spiel s1
    WHERE s1.season_id = p_season_id
      -- ... wenn es ein anderes Spiel (s2) in derselben Saison gibt, 
      -- das die gleichen Teams hat, aber eine HÖHERE ID besitzt!
      AND EXISTS (
          SELECT 1 FROM public.spiel s2
          WHERE s2.season_id = s1.season_id
            AND s2.heimteam_id = s1.heimteam_id
            AND s2.auswärtsteam_id = s1.auswärtsteam_id
            AND s2.id > s1.id 
      );
END;
$function$;

CREATE OR REPLACE FUNCTION public.cleanup_unlocked_matchday_players()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
    -- Lösche den Spieler aus allen Matchday-Snapshots des Users, die noch is_locked = false sind
    DELETE FROM public.user_matchday_players ump
    USING public.user_matchday_points ump_pts
    WHERE ump.matchday_point_id = ump_pts.id
      AND ump_pts.league_id = OLD.league_id
      AND ump_pts.user_id = OLD.user_id
      AND ump.player_id = OLD.player_id
      AND ump.is_locked = false;

    RETURN OLD;
